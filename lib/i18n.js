export function t(lang, path) {
  const dict = translations[lang] || translations.en;
  const parts = path.split('.');
  let cur = dict;
  for (const p of parts) {
    if (cur && typeof cur === 'object' && p in cur) {
      cur = cur[p];
    } else {
      return path;
    }
  }
  return cur;
}

